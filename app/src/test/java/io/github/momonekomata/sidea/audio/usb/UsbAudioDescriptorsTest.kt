package io.github.momonekomata.sidea.audio.usb

import org.junit.Assert.assertEquals
import org.junit.Assert.assertNotNull
import org.junit.Assert.assertNull
import org.junit.Test

class UsbAudioDescriptorsTest {
    // bLength counts itself.
    private fun d(vararg b: Int) = byteArrayOf((b.size + 1).toByte()) + b.map { it.toByte() }.toByteArray()

    /** A typical UAC2 dongle: clock 0x29 → input terminal 1 → output; 24-bit and 16-bit stereo alts, async with feedback. */
    private fun uac2Dongle(): ByteArray = listOf(
        d(0x02, 0x00, 0x00, 0x03, 0x01, 0x00, 0x80, 0xFA), // configuration (lengths not checked)
        d(0x04, 0x00, 0x00, 0x00, 0x01, 0x01, 0x20, 0x00), // AC interface, UAC2
        d(0x24, 0x01, 0x00, 0x02, 0x08, 0x40, 0x00, 0x00), // AC header
        d(0x24, 0x0A, 0x29, 0x03, 0x07, 0x00), // clock source 0x29
        d(0x24, 0x02, 0x01, 0x01, 0x01, 0x00, 0x29, 0x02, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00), // input terminal 1, USB streaming
        d(0x24, 0x03, 0x03, 0x02, 0x03, 0x00, 0x01, 0x29, 0x00, 0x00, 0x00), // output terminal
        d(0x04, 0x01, 0x00, 0x00, 0x01, 0x02, 0x20, 0x00), // AS interface 1, alt 0 (idle)
        d(0x04, 0x01, 0x01, 0x02, 0x01, 0x02, 0x20, 0x00), // alt 1
        d(0x24, 0x01, 0x01, 0x00, 0x01, 0x01, 0x00, 0x00, 0x00, 0x02, 0x03, 0x00, 0x00, 0x00, 0x00), // AS general: PCM, 2 ch
        d(0x24, 0x02, 0x01, 0x03, 0x18), // type I: 3-byte slots, 24 bits
        d(0x05, 0x01, 0x05, 0x40, 0x02, 0x01), // EP 0x01 OUT iso async, 576 bytes
        d(0x05, 0x81, 0x11, 0x04, 0x00, 0x04), // EP 0x81 IN iso feedback
        d(0x04, 0x01, 0x02, 0x02, 0x01, 0x02, 0x20, 0x00), // alt 2
        d(0x24, 0x01, 0x01, 0x00, 0x01, 0x01, 0x00, 0x00, 0x00, 0x02, 0x03, 0x00, 0x00, 0x00, 0x00),
        d(0x24, 0x02, 0x01, 0x02, 0x10), // 2-byte slots, 16 bits
        d(0x05, 0x01, 0x05, 0x88, 0x01, 0x01),
        d(0x05, 0x81, 0x11, 0x04, 0x00, 0x04),
        d(0x04, 0x02, 0x00, 0x01, 0x03, 0x00, 0x00, 0x00), // a HID interface for the buttons
        d(0x05, 0x83, 0x03, 0x04, 0x00, 0x08),
    ).fold(ByteArray(0)) { a, b -> a + b }

    @Test
    fun `uac2 dongle parses`() {
        val p = UsbAudioDescriptors.parse(uac2Dongle())!!
        assertEquals(true, p.uac2)
        assertEquals(0, p.controlInterface)
        assertEquals(2, p.playback.size)
        val a24 = p.playback.first { it.alternate == 1 }
        assertEquals(1, a24.interfaceNumber)
        assertEquals(2, a24.channels)
        assertEquals(3, a24.subslotBytes)
        assertEquals(24, a24.bitResolution)
        assertEquals(0x01, a24.endpointOut)
        assertEquals(576, a24.maxPacketBytes)
        assertEquals(1, a24.syncType)
        assertEquals(0x81, a24.feedbackEndpoint)
        assertEquals(0x29, p.clockFor(a24))
        assertEquals(16, p.playback.first { it.alternate == 2 }.bitResolution)
    }

    @Test
    fun `uac1 rates come from the format descriptor`() {
        val raw = listOf(
            d(0x04, 0x00, 0x00, 0x00, 0x01, 0x01, 0x00, 0x00),
            d(0x24, 0x01, 0x00, 0x01, 0x1E, 0x00, 0x01, 0x01),
            d(0x04, 0x01, 0x01, 0x01, 0x01, 0x02, 0x00, 0x00),
            d(0x24, 0x01, 0x01, 0x01, 0x01, 0x00), // AS general, PCM
            d(0x24, 0x02, 0x01, 0x02, 0x02, 0x10, 0x02, 0x44, 0xAC, 0x00, 0x80, 0xBB, 0x00), // 2 ch, 16 bit, 44.1/48
            d(0x05, 0x01, 0x09, 0xC4, 0x00, 0x01, 0x00, 0x00), // EP OUT iso adaptive, 196 bytes
        ).fold(ByteArray(0)) { a, b -> a + b }
        val p = UsbAudioDescriptors.parse(raw)!!
        assertEquals(false, p.uac2)
        val alt = p.playback.single()
        assertEquals(listOf(44_100, 48_000), alt.rates)
        assertEquals(2, alt.syncType)
        assertNull(alt.feedbackEndpoint)
    }

    @Test
    fun `non-audio devices give nothing`() {
        assertNull(UsbAudioDescriptors.parse(listOf(d(0x04, 0x00, 0x00, 0x01, 0x03, 0x00, 0x00, 0x00)).fold(ByteArray(0)) { a, b -> a + b }))
        assertNotNull(UsbAudioDescriptors.parse(uac2Dongle()))
    }
}
